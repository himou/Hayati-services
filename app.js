function revealOnScroll() {
  const revealElements = document.querySelectorAll(".reveal");
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.14 }
  );

  revealElements.forEach((element) => observer.observe(element));
}

function renderStaticTexts(lang) {
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    const value = t(lang, key);
    if (key === "footer.copy") {
      node.innerHTML = value.replace("{{year}}", String(new Date().getFullYear()));
    } else {
      node.textContent = value;
    }
  });

  document.title = t(lang, "title");
  const descriptionMeta = document.querySelector('meta[name="description"]');
  if (descriptionMeta) {
    descriptionMeta.setAttribute("content", t(lang, "metaDescription"));
  }
}

function setLanguageButtons(lang) {
  const frBtn = document.getElementById("lang-fr");
  const enBtn = document.getElementById("lang-en");
  if (!frBtn || !enBtn) return;

  frBtn.classList.toggle("is-active", lang === "fr");
  enBtn.classList.toggle("is-active", lang === "en");
}

function renderAll(lang) {
  renderStaticTexts(lang);
  renderSkills(skills, lang);
  renderToolsByLevel(toolsByLevel, lang);
  renderExperiences(experiences, lang);
  renderApplications(applications, lang);
  renderCards("project-grid", projects, "project", lang);
  renderCards("client-grid", clients, "client", lang);
  setLanguageButtons(lang);
  localStorage.setItem("portfolio_lang", lang);
}

function initLanguageSwitcher() {
  const frBtn = document.getElementById("lang-fr");
  const enBtn = document.getElementById("lang-en");
  if (!frBtn || !enBtn) return;

  frBtn.addEventListener("click", () => renderAll("fr"));
  enBtn.addEventListener("click", () => renderAll("en"));
}

const savedLang = localStorage.getItem("portfolio_lang");
const initialLang = savedLang === "en" ? "en" : "fr";

renderAll(initialLang);
revealOnScroll();
initLanguageSwitcher();