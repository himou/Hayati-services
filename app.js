function pickLocalized(value, lang) {
  if (typeof value === "string") return value;
  return value[lang] || value.fr;
}

function t(lang, key) {
  return ui[lang][key] || ui.fr[key] || key;
}

function getLevelLabel(level, lang) {
  if (level === "expert") return t(lang, "levelExpert");
  if (level === "confirme") return t(lang, "levelConfirmed");
  return t(lang, "levelBeginner");
}

function getLevelStars(level) {
  if (level === "expert") return 5;
  if (level === "confirme") return 4;
  return 2;
}

function formatYearsExperience(value, lang) {
  if (lang === "fr") {
    return `${value} ${value > 1 ? "ans" : "an"} d'expérience`;
  }
  return `${value} ${value > 1 ? "years" : "year"} of experience`;
}

function renderSkills(items, lang) {
  const root = document.getElementById("skills-grid");
  if (!root) return;

  const maxYears = Math.max(...items.map((item) => item.years), 1);
  root.innerHTML = items
    .map((item) => {
      const width = Math.round((item.years / maxYears) * 100);
      const label = getLevelLabel(item.level, lang);
      const starCount = getLevelStars(item.level);
      const stars = "★".repeat(starCount) + "☆".repeat(5 - starCount);
      const yearsLabel = formatYearsExperience(item.years, lang);
      const ariaLabel = t(lang, "levelAria").replace("{{level}}", label);

      return `
      <article class="skill-card">
        <div class="skill-header">
          <h3>${pickLocalized(item.name, lang)}</h3>
          <span class="level-badge level-${item.level}">${label}</span>
        </div>
        <p class="tool-stars" aria-label="${ariaLabel}">${stars}</p>
        <div class="level-track" aria-hidden="true">
          <span class="level-fill" style="width: ${width}%"></span>
        </div>
        <p class="tool-level-foot">${yearsLabel}</p>
      </article>
    `;
    })
    .join("");
}

