function renderExperiences(items, lang) {
  const root = document.getElementById("experience-list");
  if (!root) return;

  const toListHtml = (value) => {
    if (!value) return "";
    if (Array.isArray(value)) {
      return value.map((line) => `<li>${line}</li>`).join("");
    }
    return `<li>${value}</li>`;
  };

  const highlightEnvironmentLabels = (line) => {
    const labels = [
      "Méthodologie",
      "Méthodologies",
      "Gestionnaire de tests",
      "Outils",
      "Type d'application",
      "Niveau de tests",
      "Secteur d'activité",
      "Methodology",
      "Methodologies",
      "Test manager",
      "Tools",
      "Application type",
      "Test levels",
      "Business sector"
    ];

    const matchingLabel = labels.find((label) => line.startsWith(`${label}:`));
    if (!matchingLabel) {
      return line;
    }

    return line.replace(
      `${matchingLabel}:`,
      `<span class="xp-label">${matchingLabel}:</span>`
    );
  };

  const toEnvironmentListHtml = (value) => {
    if (!value) return "";
    if (Array.isArray(value)) {
      return value
        .map((line) => `<li>${highlightEnvironmentLabels(line)}</li>`)
        .join("");
    }
    return `<li>${highlightEnvironmentLabels(value)}</li>`;
  };

  root.innerHTML = items
    .map((item) => {
      const responsibilities = toListHtml(pickLocalized(item.responsibilities || [], lang));
      const actions = toListHtml(pickLocalized(item.actions || [], lang));
      const results = toListHtml(pickLocalized(item.results || [], lang));
      const environment = toEnvironmentListHtml(pickLocalized(item.environment || [], lang));
      const summary = item.summary ? pickLocalized(item.summary, lang) : "";
      const context = item.context ? pickLocalized(item.context, lang) : "";

      return `
      <article class="xp-entry">
        <div class="timeline-dot"></div>
        <div class="xp-content">
          <h3>${pickLocalized(item.role, lang)} - ${item.company}</h3>
          <p class="timeline-date">${pickLocalized(item.dates, lang)}</p>
          ${context ? `<div class="xp-block"><h4>${t(lang, "xp.context")}</h4><p>${context}</p></div>` : ""}
          ${responsibilities ? `<div class="xp-block"><h4>${t(lang, "xp.responsibilities")}</h4><ul>${responsibilities}</ul></div>` : ""}
          ${actions ? `<div class="xp-block"><h4>${t(lang, "xp.actions")}</h4><ul>${actions}</ul></div>` : ""}
          ${results ? `<div class="xp-block"><h4>${t(lang, "xp.results")}</h4><ul>${results}</ul></div>` : ""}
          ${environment ? `<div class="xp-block"><h4>${t(lang, "xp.environment")}</h4><ul>${environment}</ul></div>` : ""}
          ${!context && !responsibilities && !actions && !results && !environment && summary ? `<p>${summary}</p>` : ""}
        </div>
      </article>
    `;
    })
    .join("");
}

